inline uint8_t gf_mul(uint8_t a, uint8_t b) {
  uint8_t p = 0;
  for (int i = 0; i < 8; ++i) {
    if (b & 1) p ^= a;
    uint8_t hi = static_cast<uint8_t>(a & 0x80);
    a = static_cast<uint8_t>(a << 1);
    if (hi) a ^= 0x1b;
    b = static_cast<uint8_t>(b >> 1);
  }
  return p;
}


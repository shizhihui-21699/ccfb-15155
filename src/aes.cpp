// Column transforms operate in canonical (big-endian) word byte order: byte 0
// of the word is the top row of the State column, matching FIPS-197.
namespace {
// Table-driven InvMixColumns: im_t[r][b] is row r's share for byte value b.
// invmix(w) = im_t0[w>>24] ^ im_t1[(w>>16)&0xff] ^ im_t2[(w>>8)&0xff] ^ im_t3[w&0xff].
struct InvMixTables {
  uint32_t t[4][256];
  InvMixTables() {
    for (int b = 0; b < 256; ++b) {
      uint8_t v = static_cast<uint8_t>(b);
      t[0][b] = (static_cast<uint32_t>(gf_mul(v, 14)) << 24) | (static_cast<uint32_t>(gf_mul(v, 9)) << 16) |
                (static_cast<uint32_t>(gf_mul(v, 13)) << 8) | gf_mul(v, 11);
      t[1][b] = (static_cast<uint32_t>(gf_mul(v, 11)) << 24) | (static_cast<uint32_t>(gf_mul(v, 14)) << 16) |
                (static_cast<uint32_t>(gf_mul(v, 9)) << 8) | gf_mul(v, 13);
      t[2][b] = (static_cast<uint32_t>(gf_mul(v, 13)) << 24) | (static_cast<uint32_t>(gf_mul(v, 11)) << 16) |
                (static_cast<uint32_t>(gf_mul(v, 14)) << 8) | gf_mul(v, 9);
      t[3][b] = (static_cast<uint32_t>(gf_mul(v, 9)) << 24) | (static_cast<uint32_t>(gf_mul(v, 13)) << 16) |
                (static_cast<uint32_t>(gf_mul(v, 11)) << 8) | gf_mul(v, 14);
    }
  }
};
const InvMixTables& invmix_tables() {
  static InvMixTables t;
  return t;
}
}  // namespace

uint32_t aes_invmix_word(uint32_t w) {
  const InvMixTables& T = invmix_tables();
  return T.t[0][w >> 24] ^ T.t[1][(w >> 16) & 0xff] ^ T.t[2][(w >> 8) & 0xff] ^ T.t[3][w & 0xff];
}

uint32_t aes_mix_word(uint32_t w) {
  uint8_t a[4] = {static_cast<uint8_t>(w >> 24), static_cast<uint8_t>(w >> 16),
                  static_cast<uint8_t>(w >> 8), static_cast<uint8_t>(w)};
  uint8_t o[4];
  o[0] = static_cast<uint8_t>(gf_mul(a[0], 2) ^ gf_mul(a[1], 3) ^ a[2] ^ a[3]);
  o[1] = static_cast<uint8_t>(a[0] ^ gf_mul(a[1], 2) ^ gf_mul(a[2], 3) ^ a[3]);
  o[2] = static_cast<uint8_t>(a[0] ^ a[1] ^ gf_mul(a[2], 2) ^ gf_mul(a[3], 3));
  o[3] = static_cast<uint8_t>(gf_mul(a[0], 3) ^ a[1] ^ a[2] ^ gf_mul(a[3], 2));
  return (static_cast<uint32_t>(o[0]) << 24) | (static_cast<uint32_t>(o[1]) << 16) |
         (static_cast<uint32_t>(o[2]) << 8) | static_cast<uint32_t>(o[3]);
}

bool aes_expand(const uint8_t* key, size_t keylen, AesSchedule& out, bool want_dec) {
  int nk = aes_nk_from_len(keylen);
  if (!nk) return false;
  out.nk = nk;
  out.rounds = aes_rounds(nk);
  out.nwords = aes_nwords(nk);
  uint32_t* w = out.enc.data();
  for (int i = 0; i < nk; ++i) w[i] = aes_keyword(key, i);
  for (int i = nk; i < out.nwords; ++i) {
    uint32_t temp = w[i - 1];
    int r = i % nk;
    if (r == 0) {
      temp = aes_subword(aes_rotl8(temp)) ^ (static_cast<uint32_t>(kRcon[i / nk]) << 24);
    } else if (nk == 8 && r == 4) {
      temp = aes_subword(temp);
    }
    w[i] = w[i - nk] ^ temp;
  }
  if (want_dec) {
    uint32_t* d = out.dec.data();
    for (int j = 0; j < 4; ++j) d[j] = w[out.rounds * 4 + j];
    for (int r = 1; r < out.rounds; ++r)
      for (int j = 0; j < 4; ++j) d[r * 4 + j] = aes_invmix_word(w[(out.rounds - r) * 4 + j]);
    for (int j = 0; j < 4; ++j) d[out.rounds * 4 + j] = w[j];
  }
  return true;
}

bool aes_expand_words(const uint32_t* w, int nk, AesSchedule& out, bool want_dec) {
  uint8_t k[32];
  if (nk != 4 && nk != 6 && nk != 8) return false;
  for (int i = 0; i < nk * 4; ++i) k[i] = static_cast<uint8_t>(w[i / 4] >> (24 - 8 * (i % 4)));
  return aes_expand(k, static_cast<size_t>(nk) * 4, out, want_dec);
}

int aes_verify_enc(const uint32_t* w, int nk) {
  AesSchedule ref;
  if (!aes_expand_words(w, nk, ref, false)) return 0;
  int nw = ref.nwords;
  int match = 0;
  for (int i = 0; i < nw; ++i)
    if (w[i] == ref.enc[i]) ++match;
  return match;
}

bool aes_dec_to_raw(const uint32_t* d, int nk, uint8_t raw[32]) {
  if (nk != 4 && nk != 6 && nk != 8) return false;
  int rounds = aes_rounds(nk);
  int nw = aes_nwords(nk);
  uint32_t enc[kAesMaxWords];
  for (int j = 0; j < 4; ++j) enc[rounds * 4 + j] = d[j];
  for (int r = 1; r < rounds; ++r)
    for (int j = 0; j < 4; ++j) enc[(rounds - r) * 4 + j] = aes_mix_word(d[r * 4 + j]);
  for (int j = 0; j < 4; ++j) enc[j] = d[rounds * 4 + j];
  AesSchedule ref;
  if (!aes_expand_words(enc, nk, ref, true)) return false;
  for (int i = 0; i < nw; ++i)
    if (d[i] != ref.dec[i]) return false;
  aes_words_to_key(enc, nk, raw);
  return true;
}

int aes_verify_dec(const uint32_t* d, int nk) {
  uint8_t raw[32];
  if (!aes_dec_to_raw(d, nk, raw)) return 0;
  return aes_nwords(nk);
}

int aes_reconstruct_enc(std::array<int64_t, kAesMaxWords>& known, int nk) {
  int nw = aes_nwords(nk);
  bool changed = true;
  auto K = [&](int i) { return static_cast<uint32_t>(known[i]); };
  while (changed) {
    changed = false;
    for (int i = nk; i < nw; ++i) {
      int r = i % nk;
      // forward: w[i] from w[i-nk], w[i-1]
      if (known[i] < 0) {
        if (aes_enc_free_word(i, nk)) {
          if (known[i - nk] >= 0 && known[i - 1] >= 0) {
            known[i] = static_cast<int64_t>(K(i - nk) ^ K(i - 1));
            changed = true;
          }
        } else if (r == 0) {
          if (known[i - nk] >= 0 && known[i - 1] >= 0) {
            known[i] = static_cast<int64_t>(K(i - nk) ^ aes_subword(aes_rotl8(K(i - 1))) ^
                                            (static_cast<uint32_t>(kRcon[i / nk]) << 24));
            changed = true;
          }
        } else {  // nk==8, r==4
          if (known[i - nk] >= 0 && known[i - 1] >= 0) {
            known[i] = static_cast<int64_t>(K(i - nk) ^ aes_subword(K(i - 1)));
            changed = true;
          }
        }
      }
      // backward: w[i-nk] from w[i], w[i-1]
      if (known[i - nk] < 0 && known[i] >= 0 && known[i - 1] >= 0) {
        if (aes_enc_free_word(i, nk)) {
          known[i - nk] = static_cast<int64_t>(K(i) ^ K(i - 1));
          changed = true;
        } else if (r == 0) {
          known[i - nk] = static_cast<int64_t>(K(i) ^ aes_subword(aes_rotl8(K(i - 1))) ^
                                               (static_cast<uint32_t>(kRcon[i / nk]) << 24));
          changed = true;
        } else {
          known[i - nk] = static_cast<int64_t>(K(i) ^ aes_subword(K(i - 1)));
          changed = true;
        }
      }
    }
  }
  int got = 0;
  for (int i = 0; i < nk; ++i)
    if (known[i] >= 0) ++got;
  return got;
}

